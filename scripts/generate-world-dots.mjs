// Precomputes the dotted-map land grid so the 350 KB country data never ships
// to the browser. Re-run after changing the map settings:
//   npm run generate:map
import { writeFileSync } from "node:fs"
import proj4 from "proj4"
import DottedMap, { getMapJSON } from "dotted-map"

const SETTINGS = { height: 60, grid: "diagonal" }
const OUT = new URL("../src/components/ui/dotted-world-map.points.ts", import.meta.url)

const map = new DottedMap(SETTINGS)
const meta = JSON.parse(getMapJSON(SETTINGS))
const MERCATOR = "+proj=merc +lon_0=0 +x_0=0 +y_0=0 +datum=WGS84 +units=m"

const round = (n, d) => Math.round(n * 10 ** d) / 10 ** d

// Flat [x, y, lat, lng, ...] — getPoints() only gives x/y, so recover lat/lng
// the same way dotted-map's getPin() does.
const flat = []
for (const { x, y } of map.getPoints()) {
  const [lng, lat] = proj4(MERCATOR, "WGS84", [
    (x * meta.X_RANGE) / meta.width + meta.X_MIN,
    meta.Y_MAX - (y * meta.Y_RANGE) / meta.height,
  ])
  flat.push(round(x, 2), round(y, 3), round(lat, 2), round(lng, 2))
}

writeFileSync(
  OUT,
  `// Generated by scripts/generate-world-dots.mjs — do not edit by hand.
// dotted-map ${JSON.stringify(SETTINGS)}, ${flat.length / 4} land dots.

export const MAP_WIDTH = ${meta.width}
export const MAP_HEIGHT = ${meta.height}

/** Mercator bounds (metres) used to project lat/lng onto the grid */
export const MAP_BOUNDS = ${JSON.stringify({
    xMin: meta.X_MIN,
    yMax: meta.Y_MAX,
    xRange: meta.X_RANGE,
    yRange: meta.Y_RANGE,
  })}

/** Land dots as a flat [x, y, lat, lng, ...] array */
export const MAP_POINTS: readonly number[] = ${JSON.stringify(flat)}
`
)

console.log(`Wrote ${flat.length / 4} dots (${meta.width}×${meta.height})`)
